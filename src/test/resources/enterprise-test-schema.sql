-- Test schema for enterprise module with @TenantId support
-- This creates the minimal tables needed for EnterpriseLazyLoadTest

CREATE TABLE IF NOT EXISTS tax_liability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS tax_payer_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS enterprise_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS person_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(255),
    name VARCHAR(255),
    surname VARCHAR(255),
    bussiness_name VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS country (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    country_id BIGINT,
    FOREIGN KEY (country_id) REFERENCES country(id)
);

CREATE TABLE IF NOT EXISTS city (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    department_id BIGINT,
    FOREIGN KEY (department_id) REFERENCES department(id)
);

CREATE TABLE IF NOT EXISTS location (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR(255),
    city_id BIGINT,
    country_id BIGINT,
    department_id BIGINT,
    FOREIGN KEY (city_id) REFERENCES city(id),
    FOREIGN KEY (country_id) REFERENCES country(id),
    FOREIGN KEY (department_id) REFERENCES department(id)
);

CREATE TABLE IF NOT EXISTS enterprise (
    id UUID PRIMARY KEY,
    dv VARCHAR(255),
    branch VARCHAR(255),
    email VARCHAR(255),
    enterprise_type_id BIGINT,
    id_user VARCHAR(255),
    inventory_configuration_type VARCHAR(255),
    location_id BIGINT,
    logo VARCHAR(255),
    main_activity BIGINT,
    name VARCHAR(255),
    nit VARCHAR(255),
    person_type_id BIGINT,
    phone VARCHAR(255),
    secondary_activity BIGINT,
    state VARCHAR(255),
    tax_payer_type_id BIGINT,
    tenant_id VARCHAR(80),
    FOREIGN KEY (enterprise_type_id) REFERENCES enterprise_type(id),
    FOREIGN KEY (location_id) REFERENCES location(id),
    FOREIGN KEY (person_type_id) REFERENCES person_type(id),
    FOREIGN KEY (tax_payer_type_id) REFERENCES tax_payer_type(id)
);

CREATE TABLE IF NOT EXISTS enterprise_tax_liabilities (
    enterprise_id UUID NOT NULL,
    tax_liabilities_id BIGINT NOT NULL,
    PRIMARY KEY (enterprise_id, tax_liabilities_id),
    FOREIGN KEY (enterprise_id) REFERENCES enterprise(id),
    FOREIGN KEY (tax_liabilities_id) REFERENCES tax_liability(id)
);