-- THIRDS no se genera con ddl-auto en H2 (modo PostgreSQL): ePersonType es ordinal y Hibernate emite TINYINT,
-- tipo que H2 en ese modo no conoce. Se crea a mano, con SMALLINT, para ThirdsBackupRoundTripTest.
CREATE TABLE IF NOT EXISTS thirds (
    th_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    th_person_type SMALLINT,
    th_state BOOLEAN,
    th_usage_count INTEGER,
    th_id_number BIGINT,
    th_verification_number BIGINT,
    type_id_fk BIGINT,
    ent_id VARCHAR(255),
    tenant_id VARCHAR(255) NOT NULL,
    th_address VARCHAR(255),
    th_city VARCHAR(255),
    th_country VARCHAR(255),
    th_email VARCHAR(255),
    th_gender VARCHAR(255),
    th_last_names VARCHAR(255),
    th_names VARCHAR(255),
    th_phone_number VARCHAR(255),
    th_province VARCHAR(255),
    th_social_reason VARCHAR(255)
);
